# ---- 新物品的指南条目（tools/new_item.py 写进 tools/guide_items.json，mryt233 2026-11-01）
# 格式 {"zh": {"分类id": [条目, ...]}, "en": {...}}；条目字段同上，追加在对应分类末尾
def _merge_new_items():
    import json
    from pathlib import Path
    f = Path(__file__).resolve().parent / "guide_items.json"
    if not f.exists():
        return
    data = json.loads(f.read_text(encoding="utf-8"))
    for lang, cats in ((ZH, data.get("zh", {})), (EN, data.get("en", {}))):
        by_id = {c["id"]: c for c in lang}
        for cid, entries in cats.items():
            if cid in by_id:
                by_id[cid]["entries"].extend(entries)


_merge_new_items()
