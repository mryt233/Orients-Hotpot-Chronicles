PLACEHOLDER = re.compile(r"%(?:\d+\$)?s")


def main():
    en = json.loads((ROOTS[0] / MODID / "lang/en_us.json").read_text(encoding="utf-8"))
    problems = []
    for code, table in L.items():
        by_full = {full_key(k): v for k, v in table.items()}
        for wood, name in zip(TABLE_WOODS, TABLE_NAMES[code]):
            by_full[full_key(f"block.{wood}_hotpot_table")] = name
        for wood, name in zip(TABLE_WOODS, BENCH_NAMES[code]):
            by_full[full_key(f"block.{wood}_bench")] = name
        by_full[f"entity.{MODID}.seat"] = SEAT_NAMES[code]
        by_full.update(PLATE_TEXT[code])
        by_full.update(TALL_TEXT[code])
        by_full.update(SUBTAB_TEXT[code])
        by_full.update(TRIPE_TEXT[code])
        by_full[f"block.{MODID}.tall_stove_top"] = TALL_TEXT[code][f"block.{MODID}.tall_stove"]
        out = OrderedDict()
        for key, en_value in en.items():
            if key not in by_full:
                problems.append(f"{code}: 缺少 {key}")
                continue
            value = by_full[key]
            if sorted(PLACEHOLDER.findall(value)) != sorted(PLACEHOLDER.findall(en_value)):
                problems.append(f"{code}: {key} 占位符和英文不一致")
            out[key] = value
        extra = set(by_full) - set(en)
        problems += [f"{code}: 英文里没有 {k}" for k in sorted(extra)]
        for root in ROOTS:
            f = root / MODID / f"lang/{code}.json"
            f.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    print(f"已生成 {len(L)} 种语言：{', '.join(L)}（每种 {len(en)} 条）")


if __name__ == "__main__":
    main()
